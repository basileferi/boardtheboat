<?php

declare(strict_types=1);

namespace App\Entity;

use App\Entity\Concerns\TimestampableTrait;
use App\Enum\BriefStatus;
use App\Repository\CompanyBriefRepository;
use Doctrine\ORM\Mapping as ORM;
use Symfony\Bridge\Doctrine\IdGenerator\UuidGenerator;
use Symfony\Component\Uid\Uuid;

/**
 * The per-company summary that speeds up writing a motivation letter.
 *
 * Phase 1 only creates rows in status Pending and records the source URLs: generation itself
 * (rule-based first, optionally LLM-backed later) is Phase 2 and plugs in behind
 * BriefGeneratorInterface without touching this mapping.
 *
 * Every text field holds sanitised excerpts of public pages, never a full copy.
 */
#[ORM\Entity(repositoryClass: CompanyBriefRepository::class)]
#[ORM\Table(name: 'company_brief')]
#[ORM\Index(name: 'idx_brief_status_generated', columns: ['status', 'generated_at'])]
#[ORM\HasLifecycleCallbacks]
final class CompanyBrief
{
    use TimestampableTrait;

    #[ORM\Id]
    #[ORM\Column(type: 'uuid', unique: true)]
    #[ORM\GeneratedValue(strategy: 'CUSTOM')]
    #[ORM\CustomIdGenerator(class: UuidGenerator::class)]
    private ?Uuid $id = null;

    #[ORM\OneToOne(targetEntity: Company::class)]
    #[ORM\JoinColumn(nullable: false, unique: true, onDelete: 'CASCADE')]
    private Company $company;

    #[ORM\Column(length: 16, enumType: BriefStatus::class)]
    private BriefStatus $status = BriefStatus::Pending;

    #[ORM\Column(type: 'text', nullable: true)]
    private ?string $summary = null;

    #[ORM\Column(type: 'text', nullable: true)]
    private ?string $activities = null;

    #[ORM\Column(type: 'text', nullable: true)]
    private ?string $recentNews = null;

    /** @var list<string> */
    #[ORM\Column]
    private array $valuesKeywords = [];

    /** @var list<string> */
    #[ORM\Column]
    private array $letterHooks = [];

    /** @var list<string> */
    #[ORM\Column]
    private array $cvKeywords = [];

    /** @var list<string> */
    #[ORM\Column]
    private array $sourceUrls = [];

    /**
     * Identifier of the BriefGeneratorInterface implementation that produced the content.
     */
    #[ORM\Column(length: 40, nullable: true)]
    private ?string $generator = null;

    #[ORM\Column(type: 'datetime_immutable', nullable: true)]
    private ?\DateTimeImmutable $generatedAt = null;

    #[ORM\Column(type: 'text', nullable: true)]
    private ?string $failureReason = null;

    public function __construct(Company $company)
    {
        $this->company = $company;
        $this->initialiseTimestamps();
    }

    public function getId(): ?Uuid
    {
        return $this->id;
    }

    public function getCompany(): Company
    {
        return $this->company;
    }

    public function getStatus(): BriefStatus
    {
        return $this->status;
    }

    public function getSummary(): ?string
    {
        return $this->summary;
    }

    public function getActivities(): ?string
    {
        return $this->activities;
    }

    public function getRecentNews(): ?string
    {
        return $this->recentNews;
    }

    /** @return list<string> */
    public function getValuesKeywords(): array
    {
        return $this->valuesKeywords;
    }

    /** @return list<string> */
    public function getLetterHooks(): array
    {
        return $this->letterHooks;
    }

    /** @return list<string> */
    public function getCvKeywords(): array
    {
        return $this->cvKeywords;
    }

    /** @return list<string> */
    public function getSourceUrls(): array
    {
        return $this->sourceUrls;
    }

    /** @param list<string> $sourceUrls */
    public function setSourceUrls(array $sourceUrls): void
    {
        $this->sourceUrls = $sourceUrls;
    }

    public function getGenerator(): ?string
    {
        return $this->generator;
    }

    public function getGeneratedAt(): ?\DateTimeImmutable
    {
        return $this->generatedAt;
    }

    public function getFailureReason(): ?string
    {
        return $this->failureReason;
    }

    /**
     * A brief older than $maxAge is regenerated by the pipeline instead of being reused.
     */
    public function isStale(\DateInterval $maxAge, ?\DateTimeImmutable $now = null): bool
    {
        if (BriefStatus::Ready !== $this->status || null === $this->generatedAt) {
            return true;
        }

        return $this->generatedAt->add($maxAge) < ($now ?? new \DateTimeImmutable());
    }

    /**
     * @param list<string> $valuesKeywords
     * @param list<string> $letterHooks
     * @param list<string> $cvKeywords
     * @param list<string> $sourceUrls
     */
    public function markReady(
        string $generator,
        ?string $summary,
        ?string $activities,
        ?string $recentNews,
        array $valuesKeywords,
        array $letterHooks,
        array $cvKeywords,
        array $sourceUrls,
        ?\DateTimeImmutable $now = null,
    ): void {
        $this->generator = $generator;
        $this->summary = $summary;
        $this->activities = $activities;
        $this->recentNews = $recentNews;
        $this->valuesKeywords = $valuesKeywords;
        $this->letterHooks = $letterHooks;
        $this->cvKeywords = $cvKeywords;
        $this->sourceUrls = $sourceUrls;
        $this->generatedAt = $now ?? new \DateTimeImmutable();
        $this->failureReason = null;
        $this->status = BriefStatus::Ready;
    }

    public function markFailed(string $reason): void
    {
        $this->status = BriefStatus::Failed;
        $this->failureReason = $reason;
    }
}
